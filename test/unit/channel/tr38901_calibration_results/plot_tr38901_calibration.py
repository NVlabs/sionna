def _spec_version(run: dict) -> str | None:
    """Return the TR 38.901 parameter version recorded for a run."""

    value = run.get("metadata", {}).get("spec_version")
    return None if value is None else str(value)


def _sionna_label(run: dict) -> str:
    """Return a legend label that identifies the simulated model version."""

    spec_version = _spec_version(run)
    return "Sionna" if spec_version is None else f"Sionna V{spec_version}"


def _figure_title(
    scenario: str,
    phase: str,
    run: dict,
    has_reference: bool,
) -> str:
    """Return a title that separates the run from its reference workbook."""

    spec_version = _spec_version(run)
    model = "Sionna" if spec_version is None else f"Sionna TR 38.901 V{spec_version}"
    if has_reference:
        title = (
            f"{scenario} {PHASE_LABELS[phase]}: {model} vs "
            f"{PHASE_REFERENCE_LABEL[phase]}"
        )
    else:
        title = (
            f"{scenario} {PHASE_LABELS[phase]}: {model}; {PHASE_REFERENCE_LABEL[phase]}"
        )
    if len(title) > 100:
        title = title.replace(" vs ", "\nvs ", 1)
    return title


