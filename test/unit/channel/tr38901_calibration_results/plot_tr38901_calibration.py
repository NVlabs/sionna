def _resolve(path: Path) -> Path:
    """Resolve ``path`` relative to the current working directory."""

    if path.is_absolute():
        return path
    return (Path.cwd() / path).resolve()


def _run_key(scenario: str, fc_ghz: float, phase: str) -> str:
    """Return the canonical calibration run key."""

    return f"{scenario}_{fc_ghz:g}GHz_{phase}"


def _frequencies_for_phase(
    phase: str, requested_frequencies_ghz: Sequence[float] | None
) -> list[float]:
    """Return the frequency list for one calibration phase."""

    if requested_frequencies_ghz is not None:
        return [float(f) for f in requested_frequencies_ghz]
    return list(DEFAULT_FREQUENCIES_BY_PHASE[phase])


def _scenarios_for_phase(phase: str, requested_scenarios: Sequence[str]) -> list[str]:
    """Return the scenario list for one calibration phase."""

    if phase == "inf":
        scenarios = []
        for scenario in requested_scenarios:
            key = scenario.strip().lower().replace("_", "-").replace(" ", "-")
            if key in INF_SCENARIO_ALIASES:
                scenarios.append(f"InF-{INF_SCENARIO_ALIASES[key]}")
        if scenarios:
            return list(dict.fromkeys(scenarios))
        if list(requested_scenarios) == DEFAULT_SCENARIOS:
            return list(DEFAULT_INF_SCENARIOS)
        raise ValueError(
            f"The {phase} calibration is defined only for InF-SL, InF-DL, "
            "InF-SH, and InF-DH."
        )

    umi_only_phases = (
        "blockage_model_a",
        "blockage_model_b",
        "spatial_consistency_metric1_2",
        "spatial_consistency_metric3_6",
        "spatial_consistency_config2_metric1_2",
    )
    if phase in umi_only_phases:
        scenarios = [
            scenario
            for scenario in requested_scenarios
            if scenario.strip().lower()
            in ("umi", "umi-street canyon", "umi-street-canyon")
        ]
        if not scenarios:
            raise ValueError(
                f"The {phase} calibration is defined only for UMi. "
                "Include UMi in --scenarios or omit --scenarios."
            )
        return ["UMi"]
    return list(requested_scenarios)


def _load_json(path: Path) -> dict:
    """Load a JSON file."""

    return json.loads(path.read_text())


def _plot_reference_cdf(ax, ref_metric: dict) -> None:
    """Plot individual 3GPP CDF submissions and their mean curve."""

    first = True
    for curve in ref_metric.get("individual_curves", {}).values():
        ax.plot(
            curve["x"],
            curve.get("cdf", ref_metric["cdf"]),
            color="0.72",
            lw=0.8,
            alpha=0.7,
            label="3GPP companies" if first else None,
        )
        first = False
    if "x" in ref_metric and "cdf" in ref_metric:
        ax.plot(
            ref_metric["x"],
            ref_metric["cdf"],
            "k--",
            lw=1.4,
            label="3GPP mean",
        )


def _plot_reference_line(ax, ref_metric: dict) -> None:
    """Plot individual 3GPP line submissions and their mean curve."""

    first = True
    for curve in ref_metric.get("individual_curves", {}).values():
        ax.plot(
            curve.get("x", ref_metric["x"]),
            curve["y"],
            color="0.72",
            lw=0.8,
            alpha=0.7,
            label="3GPP companies" if first else None,
        )
        first = False
    if "x" in ref_metric and "y" in ref_metric:
        ax.plot(
            ref_metric["x"],
            ref_metric["y"],
            "k--",
            lw=1.4,
            label="3GPP mean",
        )


def _plot_one(
    scenario: str,
    phase: str,
    frequencies_ghz: Sequence[float],
    input_dir: Path,
    reference: dict,
    output_dir: Path,
) -> Path:
    """Plot all frequencies for one scenario and phase."""

    import matplotlib.pyplot as plt

    first_key = _run_key(scenario, frequencies_ghz[0], phase)
    first_sionna = _load_json(input_dir / f"{first_key}.json")
    metric_keys = list(first_sionna["metrics"])

    fig, axes = plt.subplots(
        len(frequencies_ghz),
        len(metric_keys),
        figsize=(4.2 * len(metric_keys), 3.0 * len(frequencies_ghz)),
        constrained_layout=True,
        squeeze=False,
    )

    for row, fc_ghz in enumerate(frequencies_ghz):
        key = _run_key(scenario, fc_ghz, phase)
        sionna = _load_json(input_dir / f"{key}.json")
        ref = reference.get(phase, {}).get(f"{scenario}-{fc_ghz:g}GHz")

        for col, metric_key in enumerate(metric_keys):
            ax = axes[row, col]
            sionna_metric = sionna["metrics"][metric_key]
            ref_metric = None if ref is None else ref["metrics"].get(metric_key)

            if ref_metric is not None:
                _plot_reference_cdf(ax, ref_metric)
            ax.plot(
                sionna_metric["x"],
                sionna_metric["cdf"],
                lw=1.7,
                color="tab:blue",
                label=_sionna_label(sionna),
            )

            if row == 0:
                ax.set_title(
                    METRIC_TITLE_OVERRIDES.get(metric_key, sionna_metric["label"])
                )
            if col == 0:
                ax.set_ylabel(f"{fc_ghz:g} GHz\nCDF [%]")
            else:
                ax.set_ylabel("CDF [%]")
            ax.grid(True, alpha=0.3)
            if row == 0 and col == 0:
                ax.legend(fontsize=8)

    first_reference = reference.get(phase, {}).get(
        f"{scenario}-{frequencies_ghz[0]:g}GHz"
    )
    fig.suptitle(
        _figure_title(
            scenario,
            phase,
            first_sionna,
            has_reference=first_reference is not None,
        )
    )
    note = PHASE_NOTES.get((scenario, phase))
    if note is not None:
        bottom = 0.08
        if phase == "spatial_consistency_config2_metric1_2":
            note = textwrap.fill(note, width=110)
            bottom = 0.115
        fig.get_layout_engine().set(rect=(0.0, bottom, 1.0, 0.88))
        fig.text(0.5, 0.02, note, ha="center", va="bottom", fontsize=8)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{scenario}_{phase}_all_freq.png"
    fig.savefig(output_path, dpi=170)
    plt.close(fig)
    return output_path


def _plot_line_one(
    scenario: str,
    phase: str,
    fc_ghz: float,
    input_dir: Path,
    reference: dict,
    output_dir: Path,
) -> Path:
    """Plot one deterministic line-curve calibration."""

    import matplotlib.pyplot as plt

    key = _run_key(scenario, fc_ghz, phase)
    sionna = _load_json(input_dir / f"{key}.json")
    ref = reference.get(phase, {}).get(f"{scenario}-{fc_ghz:g}GHz")
    metric_keys = list(sionna["metrics"])

    fig, axes = plt.subplots(
        1,
        len(metric_keys),
        figsize=(4.8 * len(metric_keys), 3.2),
        constrained_layout=True,
        squeeze=False,
    )

    for col, metric_key in enumerate(metric_keys):
        ax = axes[0, col]
        sionna_metric = sionna["metrics"][metric_key]
        ref_metric = None if ref is None else ref["metrics"].get(metric_key)

        if ref_metric is not None:
            _plot_reference_line(ax, ref_metric)
        ax.plot(
            sionna_metric["x"],
            sionna_metric["y"],
            lw=1.7,
            color="tab:blue",
            label=_sionna_label(sionna),
        )
        ax.set_title(METRIC_TITLE_OVERRIDES.get(metric_key, sionna_metric["label"]))
        ax.set_xlabel(sionna_metric.get("x_label", "Position"))
        ax.set_ylabel(sionna_metric["label"])
        ax.grid(True, alpha=0.3)
        if col == 0:
            ax.legend(fontsize=8)

    fig.suptitle(_figure_title(scenario, phase, sionna, has_reference=ref is not None))
    note = PHASE_NOTES.get((scenario, phase))
    if note is not None:
        fig.get_layout_engine().set(rect=(0.0, 0.12, 1.0, 0.86))
        fig.text(0.5, 0.03, note, ha="center", va="bottom", fontsize=8)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{scenario}_{phase}_all_freq.png"
    fig.savefig(output_path, dpi=170)
    plt.close(fig)
    return output_path


def plot_calibration_results(
    input_dir: str | Path = DEFAULT_INPUT_DIR,
    reference_json: str | Path = DEFAULT_REFERENCE_JSON,
    output_dir: str | Path = DEFAULT_OUTPUT_DIR,
    scenarios: Sequence[str] = DEFAULT_SCENARIOS,
    frequencies_ghz: Sequence[float] | None = None,
    phases: Sequence[str] = DEFAULT_PHASES,
    clean: bool = False,
) -> list[Path]:
    """Generate combined Sionna-vs-3GPP calibration figures.

    :param input_dir: Directory containing Sionna CDF JSON files.
    :param reference_json: JSON file containing 3GPP reference curves.
    :param output_dir: Directory to which generated figures are written.
    :param scenarios: Scenarios to plot.
    :param frequencies_ghz: Carrier frequencies in GHz.
    :param phases: Calibration phases to plot.
    :param clean: If `True`, remove ``output_dir`` before plotting.

    :return: List of generated figure paths.
    """

    input_dir = Path(input_dir)
    reference_json = Path(reference_json)
    output_dir = Path(output_dir)
    if clean and output_dir.exists():
        shutil.rmtree(output_dir)

    reference = _load_json(reference_json)
    output_paths = []
    for phase in phases:
        phase_scenarios = _scenarios_for_phase(phase, scenarios)
        phase_frequencies = _frequencies_for_phase(phase, frequencies_ghz)
        for scenario in phase_scenarios:
            if phase in ("blockage_model_b", "spatial_consistency_metric3_6"):
                for fc_ghz in phase_frequencies:
                    output_paths.append(
                        _plot_line_one(
                            scenario,
                            phase,
                            fc_ghz,
                            input_dir,
                            reference,
                            output_dir,
                        )
                    )
            else:
                output_paths.append(
                    _plot_one(
                        scenario,
                        phase,
                        phase_frequencies,
                        input_dir,
                        reference,
                        output_dir,
                    )
                )
    return output_paths


def main(argv: list[str] | None = None) -> None:
    """Generate combined Sionna-vs-3GPP calibration figures."""

    args = PARSER.parse_args(argv)
    output_paths = plot_calibration_results(
        input_dir=_resolve(args.input_dir),
        reference_json=_resolve(args.reference_json),
        output_dir=_resolve(args.output_dir),
        scenarios=args.scenarios,
        frequencies_ghz=args.frequencies_ghz,
        phases=args.phases,
        clean=args.clean,
    )
    for output_path in output_paths:
        print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
