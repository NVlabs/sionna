"""Plot generated Sionna TR 38.901 calibration curves.

This script reads the JSON CDF files generated by
``../tr38901_calibration.py`` and overlays them with the bundled 3GPP
reference curves from ``reference_curves.json`` when reference curves are
available. Individual company submissions are shown where they are available.
For blockage Model B and spatial-consistency metric 3/6, the script plots
line curves instead of CDFs.

Example from the Sionna repository root:

.. code-block:: bash

   python test/unit/channel/tr38901_calibration_results/plot_tr38901_calibration.py

Example from the Sionna ``test`` folder:

.. code-block:: bash

   python unit/channel/tr38901_calibration_results/plot_tr38901_calibration.py

Arguments
---------

``--scenarios``
    Scenarios to plot. Default: ``UMi UMa InH``.
``--frequencies-ghz``
    Carrier frequencies in GHz. If omitted, defaults are selected per phase:
    ``6 30 70`` for Phase 1, ``6 30 60 70`` for Phase 2 Config 1/2, and
    ``3.5 28`` for InF, and ``30`` for the blockage and
    spatial-consistency additional-feature calibrations.
``--phases``
    Calibration phases to plot. Use ``phase1``, ``config1``, and/or
    ``config2`` for the baseline calibration. Use ``blockage_model_a`` or
    ``blockage_model_b`` for the TR 38.901 Table 7.8-6 blockage
    additional-feature calibrations. Use
    ``spatial_consistency_metric1_2`` or ``spatial_consistency_metric3_6``
    for the TR 38.901 Table 7.8-5 Config1 spatial-consistency calibrations.
    Use ``spatial_consistency_config2_metric1_2`` for the Table 7.8-5
    Config2 static CDF metrics. Use ``inf`` for the normative TR 38.901 V16.1
    Table 7.8-7 10 m hall.
    Default: the three baseline phases.
``--input-dir``
    Directory containing the generated Sionna JSON files. Default:
    ``test/unit/channel/tr38901_calibration_results/cdfs`` under the Sionna
    repository root.
``--reference-json``
    JSON file containing 3GPP reference curves. Default:
    ``test/unit/channel/tr38901_calibration_results/reference_curves.json``.
``--output-dir``
    Directory for generated figures. Default:
    ``test/unit/channel/tr38901_calibration_results/figures`` under the
    Sionna repository root.
``--clean``
    Remove existing figures in the output directory before plotting. Default:
    disabled.
"""

